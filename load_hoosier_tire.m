        read_tir_value(filename, 'QDZ4'), ...
        read_tir_value(filename, 'QDZ6'), ...
        read_tir_value(filename, 'QDZ7'), ...
        read_tir_value(filename, 'QDZ8'), ...
        read_tir_value(filename, 'QDZ9'), ...
        read_tir_value(filename, 'QEZ1'), ...
        read_tir_value(filename, 'QEZ2'), ...
        read_tir_value(filename, 'QEZ3'), ...
