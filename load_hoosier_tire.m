        read_tir_value(filename, 'PKY3'), ...
        read_tir_value(filename, 'PHY1'), ...
        read_tir_value(filename, 'PHY2'), ...
        read_tir_value(filename, 'PHY3'), ...
        read_tir_value(filename, 'PVY1'), ...
        read_tir_value(filename, 'PVY2'), ...
        read_tir_value(filename, 'PVY3'), ...
        read_tir_value(filename, 'PVY4') ...
    ];

    % -------- P_mz --------
    tire.P_mz = [ ...
        read_tir_value(filename, 'QBZ1'), ...
        read_tir_value(filename, 'QBZ2'), ...
        read_tir_value(filename, 'QBZ3'), ...
